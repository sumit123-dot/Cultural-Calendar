def get_lunar_month(selected_date):
    """
    Return the Marathi Amanta lunar month
    for the selected date.

    Supported years:
        2026–2030
    """

    sorted_starts = sorted(AMANTA_MONTH_STARTS.items())

    # Before first supported date
    if selected_date < sorted_starts[0][0]:
        return "महिना उपलब्ध नाही"

    # After supported range
    if selected_date > date(2030, 12, 31):
        return "महिना उपलब्ध नाही"

    current_month = None

    for start_date, month_name in sorted_starts:
        if selected_date >= start_date:
            current_month = month_name
        else:
            break

    if current_month:
        return current_month

    return "महिना उपलब्ध नाही"